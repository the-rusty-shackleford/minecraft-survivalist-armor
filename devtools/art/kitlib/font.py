def text_mask(text: str, scale: int, stencil: bool = True) -> np.ndarray:
    """effects: returns a boolean mask of `text` in the font, each font pixel `scale` square, a
    pixel's gap between letters; a stencil leaves a bridge across each letter's middle row, as a
    cut stencil must."""
    rows = []
    for ch in text.upper():
        glyph = GLYPHS.get(ch, GLYPHS[" "])
        g = np.array([[c == "1" for c in row] for row in glyph])
        if stencil and ch not in " -":
            g = g.copy()
            g[3, 2] = False
        rows.append(np.pad(g, ((0, 0), (0, 1))))
    m = np.concatenate(rows, axis=1) if rows else np.zeros((7, 1), bool)
    return np.kron(m, np.ones((scale, scale), dtype=bool)).astype(bool)
